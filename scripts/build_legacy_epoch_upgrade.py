"""Build the reviewable SQL Editor upgrade, without connecting to any database."""
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
VERSION='20261111000100'
SOURCE=ROOT/'supabase/migrations/20261111000100_legacy_writer_epoch_guard.sql'
TARGET=ROOT/'supabase/manual/staging_upgrade_20261111000100.sql'

def build():
    source=SOURCE.read_text()
    if not source.startswith('begin;\n') or not source.endswith('commit;\n'):raise ValueError('migration must explicitly delimit its transaction')
    body=source[len('begin;\n'):-len('commit;\n')]
    tag='$pickleup_reviewed_migration_source$'
    if tag in source:raise ValueError('source delimiter collision')
    header="""-- GENERATED by scripts/build_legacy_epoch_upgrade.py; do not edit by hand.
-- STAGING ONLY. Verify Dashboard project ref rfeoeagklmaqmkcdhprb first.
-- Requires the six reviewed migrations and PostgreSQL17. Never reset or seed.
begin;
select pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('pickleup-legacy-epoch-upgrade'));
do $preflight$
declare actual text[];
begin
 if current_setting('server_version_num')::integer/10000<>17 then raise exception 'PostgreSQL major not reviewed';end if;
 if to_regclass('supabase_migrations.schema_migrations') is null then raise exception 'Missing migration history; stop';end if;
 if not exists(select 1 from information_schema.columns where table_schema='supabase_migrations' and table_name='schema_migrations' and column_name='statements' and udt_name='_text') then raise exception 'Migration history layout not reviewed';end if;
 select array_agg(version::text order by version) into actual from supabase_migrations.schema_migrations;
 if actual is distinct from array['20261029000100','20261029000200','20261030000100','20261101000100','20261101000200','20261103000100']::text[] then raise exception 'Expected exactly six baseline versions; stop and compare history';end if;
 if to_regclass('pickleup_private.legacy_write_epochs') is not null then raise exception 'Unexpected existing epoch baseline table; stop';end if;
end $preflight$;

"""
    footer="\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('"+VERSION+"','legacy_writer_epoch_guard',array["+tag+source+tag+"]::text[]);\ncommit;\nselect 'INSTALLED' as status, '"+VERSION+"' as migration_version;\n"
    return header+body+footer

if __name__=='__main__':
    expected=build()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text()!=expected:raise SystemExit('Staging SQL bundle is stale; regenerate from source')
        print('Staging SQL bundle matches reviewed source')
    else:
        TARGET.parent.mkdir(parents=True,exist_ok=True)
        TARGET.write_text(expected)
        print('Generated staging SQL bundle; no database connection')
