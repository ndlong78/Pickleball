"""Build the reviewable SQL Editor upgrade that adds self-service account deletion, without connecting to any database."""
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
VERSION='20261121000100'
SOURCE=ROOT/'supabase/migrations/20261121000100_account_deletion.sql'
TARGET=ROOT/'supabase/manual/staging_upgrade_20261121000100.sql'

def build():
    source=SOURCE.read_text()
    if not source.startswith('begin;\n') or not source.endswith('commit;\n'):raise ValueError('migration must explicitly delimit its transaction')
    body=source[len('begin;\n'):-len('commit;\n')]
    tag='$pickleup_reviewed_migration_source$'
    if tag in source:raise ValueError('source delimiter collision')
    header="""-- GENERATED by scripts/build_account_deletion_upgrade.py; do not edit by hand.
-- Verify Dashboard project ref rfeoeagklmaqmkcdhprb first. Run once in SQL Editor.
-- Requires the nine reviewed migrations and PostgreSQL17. Never reset or seed.
-- Additive: one RPC, delete_own_account; rewrites no row, changes no table, policy or grant.
begin;
select pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('pickleup-account-deletion-upgrade'));
do $preflight$
declare actual text[];
begin
 if current_setting('server_version_num')::integer/10000<>17 then raise exception 'PostgreSQL major not reviewed';end if;
 if to_regclass('supabase_migrations.schema_migrations') is null then raise exception 'Missing migration history; stop';end if;
 select array_agg(version::text order by version) into actual from supabase_migrations.schema_migrations;
 if actual is distinct from array['20261029000100','20261029000200','20261030000100','20261101000100','20261101000200','20261103000100','20261111000100','20261114000100','20261115000100']::text[] then raise exception 'Unexpected migration history %; stop',actual;end if;
 if to_regprocedure('public.delete_own_account(text)') is not null then raise exception 'delete_own_account already exists; stop';end if;
 if exists(select 1 from pg_catalog.pg_constraint c join pg_catalog.pg_namespace n on n.oid=c.connamespace
   where c.contype='f' and c.confrelid='auth.users'::regclass and n.nspname in ('public','pickleup_private') and c.confdeltype<>'c') then raise exception 'A table references auth.users without ON DELETE CASCADE; stop';end if;
end $preflight$;

"""
    footer="\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('"+VERSION+"','account_deletion',array["+tag+source+tag+"]::text[]);\ncommit;\nselect 'INSTALLED' as status, '"+VERSION+"' as migration_version;\n"
    return header+body+footer

if __name__=='__main__':
    expected=build()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text()!=expected:raise SystemExit('Staging SQL bundle is stale; regenerate from source')
        print('Staging SQL bundle matches reviewed source')
    else:
        TARGET.parent.mkdir(parents=True,exist_ok=True)
        TARGET.write_text(expected)
        print('Generated staging SQL bundle; no database connection')
