"""Build the reviewable SQL Editor upgrade that adds the video analysis store (ADR-0007), without connecting to any database."""
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
VERSION='20261128000100'
SOURCE=ROOT/'supabase/migrations/20261128000100_video_analyses.sql'
TARGET=ROOT/'supabase/manual/staging_upgrade_20261128000100.sql'

def build():
    source=SOURCE.read_text()
    if not source.startswith('begin;\n') or not source.endswith('commit;\n'):raise ValueError('migration must explicitly delimit its transaction')
    body=source[len('begin;\n'):-len('commit;\n')]
    tag='$pickleup_reviewed_migration_source$'
    if tag in source:raise ValueError('source delimiter collision')
    header="""-- GENERATED by scripts/build_video_analyses_upgrade.py; do not edit by hand.
-- Verify Dashboard project ref rfeoeagklmaqmkcdhprb first. Run once in SQL Editor.
-- Requires the ten reviewed migrations and PostgreSQL17. Never reset or seed.
-- Additive: one new table (video_analyses) and three RPCs; rewrites no existing row, table, policy, grant or function.
begin;
select pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('pickleup-video-analyses-upgrade'));
do $preflight$
declare actual text[];
begin
 if current_setting('server_version_num')::integer/10000<>17 then raise exception 'PostgreSQL major not reviewed';end if;
 if to_regclass('supabase_migrations.schema_migrations') is null then raise exception 'Missing migration history; stop';end if;
 select array_agg(version::text order by version) into actual from supabase_migrations.schema_migrations;
 if actual is distinct from array['20261029000100','20261029000200','20261030000100','20261101000100','20261101000200','20261103000100','20261111000100','20261114000100','20261115000100','20261121000100']::text[] then raise exception 'Unexpected migration history %; stop',actual;end if;
 if to_regclass('public.video_analyses') is not null or to_regprocedure('public.record_video_analysis(uuid,jsonb,integer)') is not null then raise exception 'video_analyses already exists; stop';end if;
 if not exists(select 1 from pg_catalog.pg_roles where rolname='pickleup_api' and not rolcanlogin and not rolsuper and not rolbypassrls) then raise exception 'pickleup_api role missing or privileged; stop';end if;
 if to_regprocedure('pickleup_private.caller_uid()') is null or to_regprocedure('pickleup_private.keys_ok(jsonb,text[],text[])') is null then raise exception 'Expected helper functions missing; stop';end if;
end $preflight$;

"""
    footer="\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('"+VERSION+"','video_analyses',array["+tag+source+tag+"]::text[]);\ncommit;\nselect 'INSTALLED' as status, '"+VERSION+"' as migration_version;\n"
    return header+body+footer

if __name__=='__main__':
    expected=build()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text()!=expected:raise SystemExit('Staging SQL bundle is stale; regenerate from source')
        print('Staging SQL bundle matches reviewed source')
    else:
        TARGET.parent.mkdir(parents=True,exist_ok=True)
        TARGET.write_text(expected)
        print('Generated staging SQL bundle; no database connection')
