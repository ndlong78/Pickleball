const {test,expect}=require('@playwright/test');
const fs=require('node:fs');
const core=require('../modules/content-core.js');
test.use({serviceWorkers:'block'});
const VIDEO='dQw4w9WgXcQ';
for(const width of [390,1440])test('CMS edits wording and videos, keeps scoring locked and exports a valid curriculum.js '+width,async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.goto('/Pickleball/cms/');
 await expect(page.locator('#status')).toContainText('Đã tải 80 bài');
 await expect(page.locator('#lessonList button')).toHaveCount(80);
 await page.locator('#filterText').fill('PU-001');
 await page.locator('#lessonList button[data-id="PU-001"]').click();
 for(const id of ['#f-zone','#f-assessment','#f-target'])await expect(page.locator(id)).toHaveAttribute('readonly','');
 await page.locator('[data-cue="0"]').fill('Đứng sau baseline, nhìn ô chéo trước khi giao');
 await page.locator('#addVideo').click();
 await expect(page.locator('#errors')).toContainText('ID YouTube');
 await expect(page.locator('#download')).toBeDisabled();
 await page.locator('[data-video] [data-vkey="url"]').fill('https://youtu.be/'+VIDEO);
 await page.locator('[data-video] [data-vkey="angle"]').selectOption('side');
 await page.locator('[data-video] [data-vkey="start"]').fill('3');
 await expect(page.locator('#errors li')).toHaveCount(0);
 await expect(page.locator('#changeSummary')).toContainText('Đã sửa 1 bài: PU-001');
 await expect(page.locator('#lessonList button[data-id="PU-001"]')).toContainText('đã sửa');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
 expect(download.suggestedFilename()).toBe('curriculum.js');
 const doc=core.parseCurriculum(fs.readFileSync(await download.path(),'utf8'));
 expect(core.validate(doc)).toEqual([]);
 const lesson=doc.lessons.find(l=>l.id==='PU-001');
 expect(lesson.cues[0]).toBe('Đứng sau baseline, nhìn ô chéo trước khi giao');
 expect(lesson.media).toEqual([{kind:'youtube',id:VIDEO,angle:'side',start:3}]);
 expect(lesson.revision).toBe(2);expect(lesson.assessmentVersion).toBe(1);
 // Draft survives reload and can be restored or discarded.
 await page.reload();
 await expect(page.locator('#draftBanner')).toBeVisible();
 await page.locator('#draftRestore').click();
 await expect(page.locator('#changeSummary')).toContainText('PU-001');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
 expect(overflow).toBeLessThanOrEqual(2);
});
test('CMS never registers or uses the app service worker cache',async({page})=>{
 await page.goto('/Pickleball/cms/');
 await expect(page.locator('#status')).toContainText('Đã tải');
 expect(await page.evaluate(async()=>{const keys=await caches.keys();return keys.filter(k=>k.startsWith('pickleup-'))})).toEqual([]);
 expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('pickleup_')))).toEqual([]);
});
test('Academy coach video loads nothing from YouTube until play and embeds the privacy domain',async({page})=>{
 let youtube=0;
 page.on('request',r=>{if(/youtube|ytimg|googlevideo/.test(r.url()))youtube++});
 await page.route('**/curriculum.js*',async route=>{const response=await route.fetch();await route.fulfill({response,body:(await response.text())+';window.PICKLEUP_CURRICULUM[0].media=[{kind:"youtube",id:"'+VIDEO+'",angle:"back"},{kind:"youtube",id:"'+VIDEO+'",angle:"side",start:4,end:20}];'})});
 await page.route('https://www.youtube-nocookie.com/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><title>stub</title>'}));
 await page.goto('/Pickleball/?page=academy');
 await page.locator('#academyWeek').selectOption('PU-001');
 const video=page.locator('#academyDetail [data-lesson-video]');
 await expect(video).toBeVisible();
 await expect(video.locator('[data-video-index]')).toHaveCount(2);
 expect(youtube).toBe(0);
 await video.locator('[data-video-index="1"]').click();
 await expect(video.locator('[data-video-index="1"]')).toHaveAttribute('aria-pressed','true');
 expect(youtube).toBe(0);
 await video.locator('[data-video-play]').click();
 const frame=video.locator('iframe');
 await expect(frame).toHaveAttribute('src',/^https:\/\/www\.youtube-nocookie\.com\/embed\/dQw4w9WgXcQ\?.*start=4.*end=20/);
 await page.locator('#academyWeek').selectOption('PU-002');
 await expect(page.locator('#academyDetail [data-lesson-video]')).toHaveCount(0);
});
