test('Academy coach video loads nothing from YouTube until play and embeds the privacy domain',async({page})=>{
 let youtube=0;
 page.on('request',r=>{if(/youtube|ytimg|googlevideo/.test(r.url()))youtube++});
 await page.route('**/curriculum.js*',async route=>{const response=await route.fetch();await route.fulfill({response,body:(await response.text())+';window.PICKLEUP_CURRICULUM[0].media=[{kind:"youtube",id:"'+VIDEO+'",angle:"back"},{kind:"youtube",id:"'+VIDEO+'",angle:"side",start:4,end:20}];'})});
 await page.route('https://www.youtube-nocookie.com/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><title>stub</title>'}));
 await page.goto('/Pickleball/?page=academy');
 await page.locator('#academyWeek').selectOption('PU-001');
 const video=page.locator('#academyDetail [data-lesson-video]');
 await expect(video).toBeVisible();
 await expect(video.locator('[data-video-index]')).toHaveCount(2);
 expect(youtube).toBe(0);
 await video.locator('[data-video-index="1"]').click();
 await expect(video.locator('[data-video-index="1"]')).toHaveAttribute('aria-pressed','true');
 expect(youtube).toBe(0);
 await video.locator('[data-video-play]').click();
 const frame=video.locator('iframe');
 await expect(frame).toHaveAttribute('src',/^https:\/\/www\.youtube-nocookie\.com\/embed\/dQw4w9WgXcQ\?.*start=4.*end=20/);
 await page.locator('#academyWeek').selectOption('PU-002');
 await expect(page.locator('#academyDetail [data-lesson-video]')).toHaveCount(0);
});
